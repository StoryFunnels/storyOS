/**
 * #1081 — which WORKSPACE ROLE a tool needs, so `tools/list` can leave out the tools the person's role cannot use instead of
 * advertising them and answering 403. Advertising only: the API guard still refuses the call (defence in depth).
 *
 * DERIVED, not listed. Every REST route that needs a role carries `x-min-role` in docs/api/openapi.json, generated from the very
 * `@MinRole` decorator the guard enforces. A tool needs the highest role among the routes its `reg()` block calls. A hand-kept list
 * of "admin tools" is the thing that would drift, so `role-gates.generated.ts` is produced by `pnpm sdk:generate` and a test fails
 * when it is stale (the same arrangement as the generated SDK).
 */
export type WorkspaceRole = 'guest' | 'member' | 'admin';
export const ROLE_RANK: Record<WorkspaceRole, number> = { guest: 0, member: 1, admin: 2 };

interface OpenApiLike {
  paths: Record<string, Record<string, { 'x-min-role'?: unknown } | undefined>>;
}

/** tool name -> the highest role any route it calls needs (guest-level tools are absent). Pure: source text + spec in, map out. */
export function computeToolMinRoles(toolsSource: string, openapi: OpenApiLike): Record<string, 'member' | 'admin'> {
  const out: Record<string, 'member' | 'admin'> = {};
  // one block per `reg('name', ...)` call: from its opening to the next one (or the end of the file)
  const starts = [...toolsSource.matchAll(/^ {2}reg\(\s*\n\s*'([a-z0-9_]+)'/gm)];
  for (let i = 0; i < starts.length; i++) {
    const block = toolsSource.slice(starts[i]!.index!, starts[i + 1]?.index ?? toolsSource.length);
    let need: WorkspaceRole = 'guest';
    for (const m of block.matchAll(/client\.(GET|POST|PATCH|PUT|DELETE)\(\s*'([^']+)'/g)) {
      const role = openapi.paths[m[2]!]?.[m[1]!.toLowerCase()]?.['x-min-role'];
      if (role === 'admin' || (role === 'member' && need === 'guest')) need = role;
    }
    if (need !== 'guest') out[starts[i]![1]!] = need;
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
}

export function renderGeneratedFile(roles: Record<string, 'member' | 'admin'>): string {
  const lines = Object.entries(roles).map(([name, role]) => `  ${name}: '${role}',`);
  return [
    '// GENERATED by `pnpm sdk:generate` (src/role-gates.cli.ts) from docs/api/openapi.json `x-min-role` and the `reg()` blocks in',
    '// tools.ts. Do not edit by hand: a test fails when it is stale. See role-gates.ts (ticket #1081).',
    "export const TOOL_MIN_ROLE: Record<string, 'member' | 'admin'> = {",
    ...lines,
    '};',
    '',
  ].join('\n');
}
